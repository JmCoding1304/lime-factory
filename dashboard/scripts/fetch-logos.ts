/**
 * Regenerate src/lib/logos.ts from lobehub's static SVG set (`bun run logos`).
 * One row in src/lib/providers.ts = one fetched, cleaned, inlined mark; the
 * version is pinned so a re-run is byte-reproducible. Never edit logos.ts by hand.
 */
import { join } from "node:path";
import { PROVIDERS } from "../src/lib/providers";

export const VERSION = "1.94.0";
const CDNS = [
  `https://cdn.jsdelivr.net/npm/@lobehub/icons-static-svg@${VERSION}/icons/`,
  `https://unpkg.com/@lobehub/icons-static-svg@${VERSION}/icons/`,
];

/** Strip lobehub's <title>, namespace its gradient ids as `lf-…`, refuse anything that is not a whole <svg>. */
export function clean(svg: string, key: string): string {
  const s = svg.trim().replace(/<title>[^<]*<\/title>/g, "").replace(/lobe-icons-/g, "lf-");
  if (!s.startsWith("<svg") || !s.endsWith("</svg>")) throw new Error(`${key}: not a complete <svg>`);
  return s;
}

async function fetchIcon(icon: string): Promise<string> {
  const errors: string[] = [];
  for (const base of CDNS) {
    const res = await fetch(`${base}${icon}.svg`);
    if (res.ok) return res.text();
    errors.push(`${base}${icon}.svg → ${res.status}`);
  }
  throw new Error(errors.join("; "));
}

if (import.meta.main) {
  const lines: string[] = [];
  for (const p of PROVIDERS) lines.push(`  ${JSON.stringify(p.key)}: ${JSON.stringify(clean(await fetchIcon(p.icon), p.key))},`);
  const out =
    `// Generated by \`bun run logos\` (scripts/fetch-logos.ts) from @lobehub/icons-static-svg@${VERSION}. Do not edit — edit src/lib/providers.ts and regenerate.\n` +
    `export const LOGOS: Record<string, string> = {\n${lines.join("\n")}\n};\n`;
  await Bun.write(join(import.meta.dir, "../src/lib/logos.ts"), out);
  console.log(`wrote ${PROVIDERS.length} logos to src/lib/logos.ts`);
}